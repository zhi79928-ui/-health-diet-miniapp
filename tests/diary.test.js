const assert = require('assert');
const { labelPortion, validLabelRow } = require('../utils/label-foods');
const { createDiary, addFood, setLabelFood, toggleMeal, refreshDay, dateKey, saveDay, readDays, copyPlan } = require('../utils/tracker');
let storage = {}, fail = false, definition;

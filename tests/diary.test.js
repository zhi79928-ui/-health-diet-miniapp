// Synthetic label values for deterministic arithmetic, not a recommended product.
const label = { name: '测试豆浆', state: '即饮', unit: 'g', protein: '3', carbs: '2', fat: '1', calories: '121.336', energyUnit: 'kJ' };
const row = labelPortion(label, 300);
assert.deepStrictEqual([row.protein, row.carbs, row.fat, row.calories], [9,6,3,87]);
assert.ok(validLabelRow(row)); assert.ok(!validLabelRow({ ...row, protein: 10 }));
assert.throws(() => labelPortion({ ...label, fat: '' }, 300), /都需填写/);
assert.throws(() => labelPortion({ ...label, fat: -1 }, 300));
assert.throws(() => labelPortion({ ...label, fat: 'NaN' }, 300));
assert.throws(() => labelPortion(label, 0));
assert.equal(labelPortion({ ...label, calories: '' }, 300).calories, 87);
assert.equal(labelPortion({ ...label, unit: 'mL' }, 300).unit, 'mL');
let day = createDiary(dateKey());
day = addFood(day,0,'soyMilk',300); day = addFood(day,0,'oats',60);
assert.deepStrictEqual([day.meals[0].protein,day.meals[0].carbs,day.meals[0].fat,day.meals[0].calories],[18.8,44.9,8.9,332.4]);
assert.equal(day.consumed.protein,0);
day = toggleMeal(day,0); assert.equal(day.consumed.protein,18.8);
saveDay(day); assert.equal(refreshDay(readDays()[dateKey()]).consumed.carbs,44.9);
assert.throws(() => setLabelFood(day,0,0,label,300), /已经记录/);
day = toggleMeal(day,0); day = setLabelFood(day,0,0,label,300); saveDay(day);
assert.equal(readDays()[dateKey()].meals[0].foods[0].basis.protein,3);
const copied = copyPlan(day,'2025-01-01'); assert.equal(copied.diaryOnly,true); assert.equal(copied.meals[0].logged,false);
assert.equal(copied.meals[0].foods[0].basis.protein,3);
